def _title(data: dict) -> str:
    return f"{data['reading']['label_fr']} — les cours de la semaine"


def _description(data: dict) -> str:
    summary = " ".join((data.get("summary") or "").split())
    base = summary or (f"Les meilleurs cours de Torah sur {data['reading']['label_fr']}, "
                       "sélectionnés chaque semaine.")
    return base if len(base) <= 158 else base[:155].rsplit(" ", 1)[0] + "…"


def _og_image(data: dict) -> str:
    for c in data.get("courses", []):
        if c.get("artwork"):
            return c["artwork"]
    for c in data.get("courses", []):
        if c.get("thumbnail"):
            return c["thumbnail"]
    return f"{BASE_URL}/favicon.png"


def _jsonld(data: dict, url: str, rolling: bool) -> str:
    levels = [("Accueil", f"{BASE_URL}/"), ("Cours par Paracha", f"{BASE_URL}/paracha.html"),
              ("Paracha de la semaine", f"{BASE_URL}/{ROLLING_PAGE}")]
    if not rolling:
        levels.append((data["reading"]["label_fr"], url))
    graph = {
        "@context": "https://schema.org",
        "@type": "CollectionPage",
        "name": _title(data),
        "description": _description(data),
        "url": url,
        "inLanguage": "fr",
        "datePublished": str(data.get("generated_at", ""))[:10],
        "isPartOf": {"@type": "WebSite", "name": "The Torah Podcast", "url": f"{BASE_URL}/"},
        "publisher": SITE_PUBLISHER,
        "breadcrumb": {
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": i + 1, "name": n, "item": u}
                for i, (n, u) in enumerate(levels)
            ],
        },
        "mainEntity": {
            "@type": "ItemList",
            "numberOfItems": len(data.get("courses", [])),
            "itemListElement": [
                {"@type": "ListItem", "position": i + 1, "url": c["url"], "name": c["title"]}
                for i, c in enumerate(data.get("courses", []))
            ],
        },
    }
    # `</` can never end the JSON-LD <script> block.
    return json.dumps(graph, ensure_ascii=False, indent=2).replace("</", "<\\/")


def _summary_html(summary: str) -> str:
    lines = [ln.strip() for ln in (summary or "").splitlines() if ln.strip()]
    return "\n".join(f"      <p>{esc(ln)}</p>" for ln in lines)


