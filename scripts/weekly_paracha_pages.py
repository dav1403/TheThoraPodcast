def _archives_html(weeks: list[dict], current: str) -> str:
    items = [w for w in weeks if w["week"] != current][:ARCHIVE_MAX_LINKS]
    if not items:
        return ""
    lis = "\n".join(
        f'      <li><a href="/paracha/{esc(w["week"])}.html">{esc(w["reading"]["label_fr"])} '
        f'<small>({fmt_date_fr(w["shabbat"])})</small></a></li>'
        for w in items
    )
    return (
        '  <section class="wk-archives" id="archives">\n'
        '    <h2 data-i18n="archives">Les semaines précédentes</h2>\n'
        f'    <ul>\n{lis}\n    </ul>\n'
        '  </section>\n'
    )


