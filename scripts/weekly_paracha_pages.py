def esc(s) -> str:
    return _html.escape("" if s is None else str(s), quote=True)


def fmt_date_fr(iso: str) -> str:
    try:
        d = datetime.fromisoformat(str(iso)[:10])
    except ValueError:
        return str(iso)[:10]
    return f"{d.day} {MONTHS_FR[d.month - 1]} {d.year}"


def fmt_dur(secs) -> str:
    try:
        secs = int(secs or 0)
    except (TypeError, ValueError):
        return ""
    if secs <= 0:
        return ""
    h, rem = divmod(secs, 3600)
    m = rem // 60
    return f"{h} h {m:02d}" if h else f"{m} min"


def week_url(week: str) -> str:
    return f"{BASE_URL}/paracha/{week}.html"


# --------------------------------------------------------------------------
# Data files
# --------------------------------------------------------------------------

def load_weeks(data_dir: Path = DATA_DIR) -> list[dict]:
    """Every week data file, newest Shabbat first. Unreadable files are skipped
    loudly (a corrupt file must not take the whole feed down)."""
    weeks = []
    if not data_dir.is_dir():
        return weeks
    for f in sorted(data_dir.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print(f"WARNING: skipping unreadable {f}: {exc}")
            continue
        if data.get("week") and data.get("shabbat") and data.get("courses") is not None:
            weeks.append(data)
    weeks.sort(key=lambda w: (w["shabbat"], w["week"]), reverse=True)
    return weeks


def weekly_page_link(reading: dict, ref_date=None, data_dir: Path = DATA_DIR) -> str | None:
    """URL of the rolling page when its latest week covers `reading` for the
    Shabbat on or after `ref_date` (default: today UTC), else None. Used by the
    Friday post of social_post.py, which keeps its paracha.html link otherwise
    (e.g. the Thursday run was skipped by GitHub's cron)."""
    ref = ref_date or datetime.now(timezone.utc).date()
    shabbat = (ref + timedelta(days=(5 - ref.weekday()) % 7)).isoformat()
    weeks = load_weeks(data_dir)
    if weeks and weeks[0]["shabbat"] == shabbat and weeks[0]["reading"].get("slugs") == reading.get("slugs"):
        return f"{BASE_URL}/{ROLLING_PAGE}"
    return None


# --------------------------------------------------------------------------
# Sitemap (called by generate_channel_pages.update_sitemap)
# --------------------------------------------------------------------------

def sitemap_entries(today: str, data_dir: Path = DATA_DIR) -> str:
    """<url> blocks for the rolling page + every archive page, or "".

    Deterministic from the files on disk: the rolling page is stamped with the
    build day (like the other static pages: a tolerated <lastmod> difference
    for site_compare), archives with the day they were generated."""
    weeks = load_weeks(data_dir)
    if not weeks or not Path(ROLLING_PAGE).is_file():
        return ""
    blocks = [
        "  <url>\n"
        f"    <loc>{BASE_URL}/{ROLLING_PAGE}</loc>\n"
        f"    <lastmod>{today}</lastmod>\n"
        "    <changefreq>weekly</changefreq>\n"
        "    <priority>0.8</priority>\n"
        "  </url>"
    ]
    for w in weeks:
        if not (data_dir / f"{w['week']}.html").is_file():
            continue
        blocks.append(
            "  <url>\n"
            f"    <loc>{week_url(w['week'])}</loc>\n"
            f"    <lastmod>{str(w.get('generated_at') or w['shabbat'])[:10]}</lastmod>\n"
            "    <changefreq>yearly</changefreq>\n"
            "    <priority>0.6</priority>\n"
            "  </url>"
        )
    return "\n".join(blocks) + "\n"


