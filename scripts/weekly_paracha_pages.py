def write_all(data_dir: Path = DATA_DIR, root: Path = Path(".")) -> list[str]:
    """Render the rolling page, every archive page and the feed from the data
    files. Returns the repo-relative paths written."""
    weeks = load_weeks(data_dir)
    if not weeks:
        return []
    written = []
    for w in weeks:
        out = data_dir / f"{w['week']}.html"
        out.write_text(render_page(w, weeks, rolling=False), encoding="utf-8")
        written.append(out.as_posix())
    (root / ROLLING_PAGE).write_text(render_page(weeks[0], weeks, rolling=True), encoding="utf-8")
    (root / FEED_FILE).write_text(render_feed(weeks), encoding="utf-8")
    written += [ROLLING_PAGE, FEED_FILE]
    return written
