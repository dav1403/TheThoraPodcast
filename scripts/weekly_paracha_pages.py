def _rfc822(iso: str) -> str:
    try:
        d = datetime.fromisoformat(str(iso).replace("Z", "+00:00"))
    except ValueError:
        d = datetime.fromisoformat(str(iso)[:10])
    if d.tzinfo is None:
        d = d.replace(tzinfo=timezone.utc)
    return format_datetime(d.astimezone(timezone.utc), usegmt=True)


def _item_html(w: dict) -> str:
    parts = [f"<p>{esc(ln.strip())}</p>" for ln in (w.get("summary") or "").splitlines() if ln.strip()]
    lis = "".join(
        f'<li><a href="{esc(c["url"])}">{esc(c["title"])}</a> — {esc(c["rav"])}</li>'
        for c in w.get("courses", [])
    )
    parts.append(f"<ul>{lis}</ul>")
    parts.append(f'<p><a href="{esc(week_url(w["week"]))}">Écouter la sélection sur The Torah Podcast</a></p>')
    return "".join(parts)


def render_feed(weeks: list[dict]) -> str:
    items = []
    for w in weeks[:FEED_MAX_ITEMS]:
        url = week_url(w["week"])
        items.append(
            "    <item>\n"
            f"      <title>{esc(w['reading']['label_fr'])} — les cours de la semaine</title>\n"
            f"      <link>{esc(url)}</link>\n"
            f'      <guid isPermaLink="true">{esc(url)}</guid>\n'
            f"      <pubDate>{_rfc822(w.get('generated_at') or w['shabbat'])}</pubDate>\n"
            f"      <description>{esc(_item_html(w))}</description>\n"
            "    </item>"
        )
    last = _rfc822(weeks[0].get("generated_at") or weeks[0]["shabbat"]) if weeks else ""
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">\n'
        "  <channel>\n"
        "    <title>The Torah Podcast — la paracha de la semaine</title>\n"
        f"    <link>{BASE_URL}/{ROLLING_PAGE}</link>\n"
        f'    <atom:link href="{BASE_URL}/{FEED_FILE}" rel="self" type="application/rss+xml"/>\n'
        "    <description>Chaque jeudi, une sélection des meilleurs cours de Torah sur la "
        "paracha (ou la fête) de la semaine, avec un court résumé.</description>\n"
        "    <language>fr</language>\n"
        f"    <lastBuildDate>{last}</lastBuildDate>\n"
        + ("\n".join(items) + "\n" if items else "")
        + "  </channel>\n</rss>\n"
    )


